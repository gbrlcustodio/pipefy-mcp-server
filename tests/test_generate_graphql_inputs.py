"""Tests for scripts/generate_graphql_inputs.py."""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

_REPO_ROOT = Path(__file__).resolve().parents[1]
_SCRIPT = _REPO_ROOT / "scripts" / "generate_graphql_inputs.py"
_spec = importlib.util.spec_from_file_location("generate_graphql_inputs", _SCRIPT)
assert _spec and _spec.loader
_gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_gen)


def _snapshot() -> dict:
    return json.loads(_gen.SNAPSHOT_PATH.read_text())


# --- the drift guard itself -------------------------------------------------


def test_generated_models_match_the_committed_snapshot():
    """The check CI runs, run here so a stale commit fails the suite too."""
    assert _gen.command_check() == 0


def test_every_root_type_is_in_the_snapshot():
    snapshot = _snapshot()
    assert sorted(_gen.ROOT_INPUT_TYPES) == snapshot["roots"]
    for root in _gen.ROOT_INPUT_TYPES:
        assert root in snapshot["inputs"]


def test_snapshot_is_closed_over_its_references():
    """Every input object and enum a field names is itself in the snapshot."""
    snapshot = _snapshot()
    known = set(snapshot["inputs"]) | set(snapshot["enums"]) | set(_gen.SCALAR_TYPES)
    for name, spec in snapshot["inputs"].items():
        for field in spec["fields"]:
            referenced = _gen._named_type(field["type"])
            assert referenced in known, f"{name}.{field['name']} -> {referenced}"


# --- type mapping -----------------------------------------------------------


@pytest.mark.parametrize(
    ("type_ref", "expected", "required"),
    [
        ("String", "str", False),
        ("String!", "str", True),
        ("ID!", "PipefyGraphQLId", True),
        ("Int", "int", False),
        ("Float", "float", False),
        ("Boolean", "bool", False),
        ("JSON", "GraphQLJson", False),
        # A nullable list of nullable strings, faithful to `[String]`.
        ("[String]", "list[str | None]", False),
        # `[String!]!` keeps both non-nulls: no `| None` inside or out.
        ("[String!]!", "list[str]", True),
        # `[[ID]]` — the shape createFieldCondition uses for expressions_structure.
        ("[[ID]]", "list[list[PipefyGraphQLId | None] | None]", False),
        ("ConditionInput", "ConditionInput", False),
        # The one lowercase type name in the schema takes the Python spelling.
        ("createFieldConditionInput", "CreateFieldConditionInput", False),
        # A GraphQL enum is a soft enum: typed str, any value sent.
        ("Colors", "str", False),
    ],
)
def test_python_type_mapping(type_ref, expected, required):
    assert _gen.python_type(type_ref, _snapshot()) == (expected, required)


def test_unmapped_scalar_is_a_hard_failure():
    """A new custom scalar must be mapped deliberately, not guessed at."""
    with pytest.raises(SystemExit, match="Money"):
        _gen.python_type("Money", {"inputs": {}, "enums": {}})


