# --- snapshot building ------------------------------------------------------


def _schema_type(name, kind, fields=None, enum_values=None):
    return {
        "name": name,
        "kind": kind,
        "description": None,
        "enumValues": [{"name": v} for v in (enum_values or [])] or None,
        "inputFields": fields,
    }


def _scalar_ref(name, non_null=False):
    ref = {"kind": "SCALAR", "name": name, "ofType": None}
    return {"kind": "NON_NULL", "name": None, "ofType": ref} if non_null else ref


def test_build_snapshot_walks_transitively(monkeypatch):
    monkeypatch.setattr(_gen, "ROOT_INPUT_TYPES", ("RootInput",))
    schema = [
        _schema_type(
            "RootInput",
            "INPUT_OBJECT",
            [
                {
                    "name": "nested",
                    "description": None,
                    "defaultValue": None,
                    "type": {
                        "kind": "INPUT_OBJECT",
                        "name": "NestedInput",
                        "ofType": None,
                    },
                },
                {
                    "name": "shade",
                    "description": None,
                    "defaultValue": None,
                    "type": {"kind": "ENUM", "name": "Shade", "ofType": None},
                },
            ],
        ),
        _schema_type(
            "NestedInput",
            "INPUT_OBJECT",
            [
                {
                    "name": "id",
                    "description": None,
                    "defaultValue": None,
                    "type": _scalar_ref("ID", non_null=True),
                }
            ],
        ),
        _schema_type("Shade", "ENUM", enum_values=["light", "dark"]),
        _schema_type("Unrelated", "INPUT_OBJECT", []),
    ]
    snapshot = _gen.build_snapshot(schema)
    assert set(snapshot["inputs"]) == {"RootInput", "NestedInput"}
    assert snapshot["enums"] == {"Shade": ["light", "dark"]}
    assert snapshot["inputs"]["NestedInput"]["fields"][0]["type"] == "ID!"


def test_build_snapshot_rejects_a_root_that_is_not_an_input_object(monkeypatch):
    monkeypatch.setattr(_gen, "ROOT_INPUT_TYPES", ("Pipe",))
    with pytest.raises(SystemExit, match="Pipe is not an INPUT_OBJECT"):
        _gen.build_snapshot([_schema_type("Pipe", "OBJECT")])


